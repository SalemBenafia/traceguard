import assert from 'node:assert/strict';
import { describe, test } from 'node:test';
import {
  auditPackTitle,
  buildAuditPackPage,
  escapeStorage,
  isValidSpaceKey,
  NEXT_STEPS,
  normalizeReleaseName,
  summarizeAudit,
  titleForAttempt,
} from '../src/engine/auditPack.js';

const row = (key, rag, overrides = {}) => ({
  req_key: key,
  summary: `Summary ${key}`,
  owner_name: 'Demo Owner',
  owner_team: 'Firmware',
  rag,
  gaps: [],
  ...overrides,
});

const page = (matrix, overrides = {}) =>
  buildAuditPackPage({
    projectKey: 'SPF',
    releaseName: '',
    matrix,
    jiraBaseUrl: 'https://example.atlassian.net',
    scanId: 'scan-123',
    generatedOn: '2026-11-22',
    hiddenCount: 0,
    ...overrides,
  });

describe('escapeStorage', () => {
  test('escapes every XML special character', () => {
    assert.equal(escapeStorage(`<a href="x">Tom & 'Jerry'</a>`), '&lt;a href=&quot;x&quot;&gt;Tom &amp; &#39;Jerry&#39;&lt;/a&gt;');
  });

  test('escapes an ampersand only once', () => {
    assert.equal(escapeStorage('&amp;'), '&amp;amp;');
  });

  test('removes characters that are invalid in XML', () => {
    assert.equal(escapeStorage('a\u0000b\u0008c￾d\uD800e'), 'abcde');
  });

  test('keeps tabs, new lines and non-English text', () => {
    assert.equal(escapeStorage('a\tb\nçé 日本 😀'), 'a\tb\nçé 日本 😀');
  });

  test('handles empty values', () => {
    assert.equal(escapeStorage(null), '');
    assert.equal(escapeStorage(undefined), '');
  });
});

describe('titles and inputs', () => {
  test('uses the release name', () => {
    assert.equal(auditPackTitle({ projectKey: 'SPF', releaseName: '2.4.0', day: '2026-11-22' }), 'Audit pack - SPF - 2.4.0');
  });

  test("uses today's date without a release", () => {
    assert.equal(auditPackTitle({ projectKey: 'SPF', releaseName: '', day: '2026-11-22' }), 'Audit pack - SPF - 2026-11-22');
  });

  test('adds a number for later attempts', () => {
    assert.equal(titleForAttempt('Audit pack', 1), 'Audit pack');
    assert.equal(titleForAttempt('Audit pack', 2), 'Audit pack (2)');
    assert.equal(titleForAttempt('Audit pack', 3), 'Audit pack (3)');
  });

  test('cleans a release name', () => {
    assert.equal(normalizeReleaseName('  2.4\n.0 '), '2.4 .0');
    assert.equal(normalizeReleaseName(42), '');
    assert.equal(normalizeReleaseName('x'.repeat(300)).length, 100);
  });

  test('accepts only letters and digits in a space key', () => {
    assert.equal(isValidSpaceKey('QA1'), true);
    assert.equal(isValidSpaceKey('QA-1'), false);
    assert.equal(isValidSpaceKey('~me'), false);
    assert.equal(isValidSpaceKey(''), false);
  });
});

describe('summarizeAudit', () => {
  const totals = { total: 20, green: 9, amber: 4, red: 7 };

  test('states the real counts and percentage', () => {
    assert.equal(
      summarizeAudit({ projectKey: 'SPF', releaseName: '', totals }),
      'Project SPF has 20 requirements: 9 audit-ready (Green), 4 needing attention (Amber) and 7 blocking the audit (Red). Overall, the project is 45% audit-ready.',
    );
  });

  test('includes the release', () => {
    assert.match(summarizeAudit({ projectKey: 'SPF', releaseName: '2.4.0', totals }), /20 requirements for release 2\.4\.0:/);
  });

  test('uses the singular for one requirement', () => {
    const one = { total: 1, green: 1, amber: 0, red: 0 };

    assert.match(summarizeAudit({ projectKey: 'SPF', releaseName: '', totals: one }), /has 1 requirement:/);
  });
});

describe('buildAuditPackPage', () => {
  const gap = (code, severity = 'red') => ({ code, severity, message: `Message ${code}` });

  test('has every section in order', () => {
    const html = page([row('SPF-1', 'green')]);
    const positions = ['Project SPF has', 'ac:name="info"', '<table>', 'Open gaps and next steps', 'Generated by TraceGuard'].map((text) => html.indexOf(text));

    assert.ok(positions.every((position) => position >= 0));
    assert.deepEqual(positions, [...positions].sort((a, b) => a - b));
  });

  test('the info panel shows totals and audit-ready percent', () => {
    const html = page([row('SPF-1', 'green'), row('SPF-2', 'red', { gaps: [gap('NO_TEST')] })]);

    assert.match(html, /Total: 2 \| Green: 1 \| Amber: 0 \| Red: 1 \| Audit-ready: 50%/);
  });

  test('the table lists all requirements, red first, with Jira links', () => {
    const html = page([row('SPF-1', 'green'), row('SPF-10', 'red'), row('SPF-2', 'amber')]);

    assert.equal(html.match(/<tr>/g).length, 4);
    assert.ok(html.indexOf('>SPF-10</a>') < html.indexOf('>SPF-2</a>'));
    assert.ok(html.indexOf('>SPF-2</a>') < html.indexOf('>SPF-1</a>'));
    assert.ok(html.includes('<a href="https://example.atlassian.net/browse/SPF-1">SPF-1</a>'));
  });

  test('shows owner, team, and an unassigned owner', () => {
    const html = page([row('SPF-1', 'green'), row('SPF-2', 'amber', { owner_name: null, owner_team: null })]);

    assert.ok(html.includes('<td>Demo Owner</td><td>Firmware</td>'));
    assert.ok(html.includes('<td>Unassigned</td><td>No team found</td>'));
  });

  test('uses Green, Yellow and Red status macros', () => {
    const html = page([row('SPF-1', 'green'), row('SPF-2', 'amber'), row('SPF-3', 'red')]);

    for (const [colour, title] of [['Green', 'Green'], ['Yellow', 'Amber'], ['Red', 'Red']]) {
      assert.ok(html.includes(`<ac:structured-macro ac:name="status"><ac:parameter ac:name="colour">${colour}</ac:parameter><ac:parameter ac:name="title">${title}</ac:parameter></ac:structured-macro>`));
    }
  });

  test('lists open gaps with a next step', () => {
    const html = page([row('SPF-3', 'red', { gaps: [gap('TEST_FAILED')] })]);

    assert.ok(html.includes('Message TEST_FAILED'));
    assert.ok(html.includes(NEXT_STEPS.TEST_FAILED));
  });

  test('every gap code has a next step', () => {
    for (const code of ['NO_IMPLEMENTATION', 'NO_TEST', 'TEST_FAILED', 'STALE_VERIFICATION', 'TEST_NOT_RUN', 'IMPLEMENTATION_OPEN', 'NO_OWNER']) {
      assert.ok(NEXT_STEPS[code], code);
    }
  });

  test('says when there are no open gaps', () => {
    assert.match(page([row('SPF-1', 'green')]), /<p>No open gaps\.<\/p>/);
  });

  test('has the exact footer', () => {
    assert.ok(page([row('SPF-1', 'green')]).includes('Generated by TraceGuard on 2026-11-22 from scan scan-123'));
  });

  test('states how many requirements were left out', () => {
    assert.match(page([row('SPF-1', 'green')], { hiddenCount: 2 }), /2 requirements were left out/);
    assert.doesNotMatch(page([row('SPF-1', 'green')]), /left out/);
  });

  test('escapes all Jira text', () => {
    const attack = '</td><ac:structured-macro ac:name="html"><script>alert(1)</script>&';
    const html = page([
      row('SPF-1', 'red', {
        summary: attack,
        owner_name: attack,
        owner_team: attack,
        gaps: [{ code: 'NO_TEST', severity: 'red', message: attack }],
      }),
    ], { releaseName: attack });

    assert.doesNotMatch(html, /<script>/);
    assert.doesNotMatch(html, /ac:name="html"/);
    assert.ok(html.includes('&lt;script&gt;'));
  });
});
